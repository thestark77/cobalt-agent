# ── Cron helpers ────────────────────────────────────────────────────────────

CRON_MARKER="# cobalt-routing: patch-verify (managed by install.sh)"
CRON_ENV_FILE="$HOME/.hermes/cobalt-cron.env"

write_cron_env_file() {
    # Persist Telegram + Engram env so the cron job can source them at fire time.
    # File is mode 600 because it can contain tokens.
    mkdir -p "$(dirname "$CRON_ENV_FILE")"
    umask 077
    {
        echo "# Generated by cobalt-agent install.sh — managed file. Re-run install to update."
        [ -n "${TELEGRAM_BOT_TOKEN:-}" ] && echo "export TELEGRAM_BOT_TOKEN=\"${TELEGRAM_BOT_TOKEN}\""
        [ -n "${TELEGRAM_CHAT_ID:-}" ]   && echo "export TELEGRAM_CHAT_ID=\"${TELEGRAM_CHAT_ID}\""
        [ -n "${ENGRAM_CLOUD_SERVER:-}" ] && echo "export ENGRAM_CLOUD_SERVER=\"${ENGRAM_CLOUD_SERVER}\""
        [ -n "${ENGRAM_CLOUD_TOKEN:-}" ]  && echo "export ENGRAM_CLOUD_TOKEN=\"${ENGRAM_CLOUD_TOKEN}\""
        [ -n "${ENGRAM_CLOUD_AUTOSYNC:-}" ] && echo "export ENGRAM_CLOUD_AUTOSYNC=\"${ENGRAM_CLOUD_AUTOSYNC}\""
    } > "$CRON_ENV_FILE"
    chmod 600 "$CRON_ENV_FILE"
}

build_cron_entry() {
    # Daily 09:00 local — runs the verifier through the env file.
    local verify_script="$1"
    echo "0 9 * * * . $CRON_ENV_FILE && /usr/bin/env bash $verify_script >> $HOME/.hermes/cobalt-cron.log 2>&1 $CRON_MARKER"
}

setup_verify_cron() {
    if [ "${COBALT_INSTALL_CRON:-1}" = "0" ]; then
        log "COBALT_INSTALL_CRON=0 — skipping cron setup"
        return 0
    fi

    if [ -z "${TELEGRAM_BOT_TOKEN:-}" ] || [ -z "${TELEGRAM_CHAT_ID:-}" ]; then
        warn "TELEGRAM_BOT_TOKEN/TELEGRAM_CHAT_ID not set — patch-verify cron skipped"
        warn "Export both and re-run installer to enable VPS-side patch monitoring."
        return 0
    fi

    if ! command -v crontab &>/dev/null; then
        warn "crontab not found — patch-verify cron skipped (install cron and re-run)"
        return 0
    fi

    local verify_script="$HOME/.hermes/cobalt-verify-patch.sh"
    cp "$COBALT_TMP/scripts/verify-patch.sh" "$verify_script"
    chmod +x "$verify_script"

    # Persist the patch applicator inside HERMES_HOME so the verifier can
    # find it even after the user deletes the cloned cobalt-agent repo.
    # verify-patch.sh probes this path before falling back to COBALT_HOME.
    mkdir -p "$HOME/.hermes/cobalt-patches"
    if [ -f "$COBALT_TMP/patches/apply_routing_patch.py" ]; then
        cp "$COBALT_TMP/patches/apply_routing_patch.py" \
           "$HOME/.hermes/cobalt-patches/apply_routing_patch.py"
    fi

    write_cron_env_file
    local new_entry
    new_entry=$(build_cron_entry "$verify_script")

    # Idempotent crontab edit: strip any prior cobalt entry, append new one.
    local existing
    existing=$(crontab -l 2>/dev/null || true)
    local without_old
    without_old=$(echo "$existing" | grep -v -F "$CRON_MARKER" || true)

    if [ "$without_old" = "$existing" ] && echo "$existing" | grep -qF "$CRON_MARKER"; then
        # nothing to strip
        :
    fi

    local desired
    if [ -n "$without_old" ]; then
        desired=$(printf "%s\n%s\n" "$without_old" "$new_entry")
    else
        desired="$new_entry"
    fi

    # Compare with current crontab — only update if changed
    if [ "$existing" = "$desired" ]; then
        log "Cron job already up to date (daily 09:00)"
        return 0
    fi

    echo "$desired" | crontab -
    if echo "$existing" | grep -qF "$CRON_MARKER"; then
        log "Cron job updated (daily 09:00 — Telegram notifications)"
    else
        log "Cron job installed (daily 09:00 — Telegram notifications)"
    fi
}

_install_engram_binary() {
    # Auto-installer for the Engram CLI/MCP binary.
    # Pulls the latest official release tarball, extracts to ~/.local/bin/engram,
    # and verifies the resulting binary runs. Idempotent + safe to re-run.
    local arch os asset url tmp_dir
    case "$(uname -s)" in
        Linux)  os="linux"   ;;
        Darwin) os="darwin"  ;;
        *)
            warn "Unsupported OS '$(uname -s)' for auto-install. Install engram manually."
            return 1
            ;;
    esac
    case "$(uname -m)" in
        x86_64|amd64) arch="amd64" ;;
        aarch64|arm64) arch="arm64" ;;
        *)
            warn "Unsupported arch '$(uname -m)' for auto-install. Install engram manually."
            return 1
            ;;
    esac

    log "Resolving latest Engram release..."
    local release_json tag tarball
    release_json=$(curl -fsSL https://api.github.com/repos/Gentleman-Programming/engram/releases/latest 2>/dev/null || true)
    if [ -z "$release_json" ]; then
        warn "Could not fetch Engram release metadata (network?). Skipping auto-install."
        return 1
    fi

    tag=$(echo "$release_json" | python3 -c "import sys,json; print(json.load(sys.stdin).get('tag_name',''))" 2>/dev/null)
    if [ -z "$tag" ]; then
        warn "Could not parse Engram release tag. Skipping auto-install."
        return 1
    fi

    # Tarball name pattern: engram_<version>_<os>_<arch>.tar.gz  (version w/o the 'v')
    local version="${tag#v}"
    tarball="engram_${version}_${os}_${arch}.tar.gz"
    url="https://github.com/Gentleman-Programming/engram/releases/download/${tag}/${tarball}"

    tmp_dir=$(mktemp -d) || return 1
    log "Downloading Engram ${tag} (${os}/${arch})..."
    if ! curl -fsSL "$url" -o "$tmp_dir/$tarball"; then
        warn "Engram download failed from $url"
        rm -rf "$tmp_dir"
        return 1
    fi

    tar -xzf "$tmp_dir/$tarball" -C "$tmp_dir" 2>/dev/null || {
        warn "Engram tarball extraction failed"
        rm -rf "$tmp_dir"
        return 1
    }

    local extracted_bin
    extracted_bin=$(find "$tmp_dir" -maxdepth 2 -name engram -type f -executable 2>/dev/null | head -n1)
    if [ -z "$extracted_bin" ]; then
        warn "engram binary not found inside the tarball"
        rm -rf "$tmp_dir"
        return 1
    fi

    mkdir -p "$HOME/.local/bin"
    mv "$extracted_bin" "$HOME/.local/bin/engram"
    chmod +x "$HOME/.local/bin/engram"
    rm -rf "$tmp_dir"

    if [[ ":$PATH:" != *":$HOME/.local/bin:"* ]]; then
        if ! grep -q '\.local/bin' "$HOME/.bashrc" 2>/dev/null; then
            echo 'export PATH="$HOME/.local/bin:$PATH"' >> "$HOME/.bashrc"
        fi
        export PATH="$HOME/.local/bin:$PATH"
    fi
    hash -r 2>/dev/null || true

    if "$HOME/.local/bin/engram" --version &>/dev/null; then
        log "Engram installed: $("$HOME/.local/bin/engram" --version 2>&1 | head -n1)"
        return 0
    else
        warn "Engram binary installed at ~/.local/bin/engram but failed --version check"
        return 1
    fi
}

check_engram_binary() {
    # Soft-detect first (PATH miss is common right after installing to ~/.local/bin)
    if command -v engram &>/dev/null; then
        log "engram binary found: $(command -v engram)"
        return 0
    fi
    if [ -x "$HOME/.local/bin/engram" ]; then
        export PATH="$HOME/.local/bin:$PATH"
        hash -r 2>/dev/null || true
        log "engram binary found: $HOME/.local/bin/engram (added ~/.local/bin to PATH)"
        return 0
    fi

    # Only auto-install when the user actually wants Engram (env vars present);
    # otherwise we'd download a binary nobody asked for.
    if [ "${ENGRAM_ENABLED:-0}" != "1" ]; then
        warn "engram binary not in PATH and ENGRAM_CLOUD_SERVER/TOKEN not set."
        warn "Export them and re-run installer to enable memory."
        return 1
    fi

    log "engram binary missing but Engram Cloud env vars set — auto-installing..."
    if _install_engram_binary; then
        return 0
    fi
    warn "Engram auto-install failed. Memory MCP will be inactive."
    warn "Install manually: https://github.com/Gentleman-Programming/engram (Homebrew or download from Releases)."
    return 1
}

# ── Helpers ─────────────────────────────────────────────────────────────────

version_tuple() {
    local v="$1"
    local major minor patch
    major=$(echo "$v" | cut -d. -f1)
    minor=$(echo "$v" | cut -d. -f2)
    patch=$(echo "$v" | cut -d. -f3)
    printf "%03d%03d%03d" "${major:-0}" "${minor:-0}" "${patch:-0}"
}

version_gte() { [ "$(version_tuple "$1")" -ge "$(version_tuple "$2")" ]; }
version_gt()  { [ "$(version_tuple "$1")" -gt "$(version_tuple "$2")" ]; }

read_hermes_version() {
    local pyproject="$HERMES_AGENT_DIR/pyproject.toml"
    if [ -f "$pyproject" ]; then
        python3 -c "
import tomllib, sys
with open('$pyproject', 'rb') as f:
    data = tomllib.load(f)
print(data.get('project', {}).get('version', '0.0.0'))
" 2>/dev/null || echo "0.0.0"
    else
        echo "0.0.0"
    fi
}

check_hermes_compat() {
    local ver="$1"
    if version_gte "$ver" "$HERMES_ERROR_FROM"; then
        err "Hermes $ver is INCOMPATIBLE with cobalt-routing v${COBALT_VERSION}"
        err "cobalt-routing was tested on Hermes $HERMES_TESTED_VERSION"
        err "Hermes >= $HERMES_ERROR_FROM introduces breaking changes."
        err "Wait for a cobalt-agent update or pin Hermes to a compatible version."
        exit 1
    fi
    if version_gte "$ver" "$HERMES_WARN_FROM"; then
        warn "Hermes $ver is ABOVE the tested version ($HERMES_TESTED_VERSION)"
        warn "cobalt-routing may still work, but has not been validated on this version."
        warn "Proceeding anyway — report issues at https://github.com/thestark77/cobalt-agent/issues"
        echo ""
    fi
}

