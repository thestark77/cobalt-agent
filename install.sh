header "Step 1/10: Prerequisites"
# ============================================================================

check_cmd() {
    if ! command -v "$1" &>/dev/null; then
        err "$1 not found. Please install it first."
        return 1
    fi
    log "$1 found: $(command -v "$1")"
}

MISSING=0
check_cmd git || MISSING=1
check_cmd python3 || MISSING=1
check_cmd curl || MISSING=1
check_cmd pip3 || check_cmd pip || MISSING=1

PYTHON_VERSION=$(python3 -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')
PYTHON_MAJOR=$(echo "$PYTHON_VERSION" | cut -d. -f1)
PYTHON_MINOR=$(echo "$PYTHON_VERSION" | cut -d. -f2)

if [ "$PYTHON_MAJOR" -lt 3 ] || ([ "$PYTHON_MAJOR" -eq 3 ] && [ "$PYTHON_MINOR" -lt 11 ]); then
    err "Python 3.11+ required (found $PYTHON_VERSION)"
    MISSING=1
fi

if ! python3 -c "import venv" 2>/dev/null; then
    err "python3-venv not found. Install it: sudo apt install python${PYTHON_VERSION}-venv"
    MISSING=1
else
    log "python3-venv module available"
fi

if [ "$MISSING" -eq 1 ]; then
    err "Missing prerequisites. Install them and re-run."
    exit 1
fi

log "Python $PYTHON_VERSION OK"

HAS_NPM=0
if command -v npm &>/dev/null || command -v npx &>/dev/null; then
    HAS_NPM=1
    log "npm found"
else
    warn "npm not found. OpenCode CLI won't be installed (you can configure provider manually)"
fi

# ============================================================================
header "Step 2/10: Hermes Agent"
# ============================================================================

VENV_DIR="$HERMES_AGENT_DIR/venv"

if [ -f "$HERMES_AGENT_DIR/pyproject.toml" ]; then
    CURRENT_VER=$(read_hermes_version)
    log "Hermes Agent found at $HERMES_AGENT_DIR (v$CURRENT_VER)"

    check_hermes_compat "$CURRENT_VER"

    if [ "$IS_UPDATE" -eq 1 ]; then
        log "Updating Hermes Agent..."
        cd "$HERMES_AGENT_DIR"

        # The cobalt source patch in tools/delegate_tool.py creates a local
        # diff that makes `git pull` refuse to merge upstream commits with
        # "Your local changes would be overwritten". Discard the patched
        # file before pulling — Step 4 re-applies the patch on the freshly
        # pulled code afterwards. This keeps the upgrade path automatic for
        # future Hermes versions (0.14.x, etc.).
        if grep -q "# cobalt-routing patch" tools/delegate_tool.py 2>/dev/null; then
            if git checkout -- tools/delegate_tool.py 2>/dev/null; then
                log "Cleared local patch from delegate_tool.py to allow pull (Step 4 re-applies)"
            fi
        fi

        git fetch origin 2>/dev/null || warn "Could not fetch updates (network issue?)"

        if [ -n "$HERMES_TESTED_TAG" ]; then
            git checkout "$HERMES_TESTED_TAG" 2>/dev/null || {
                warn "Tag $HERMES_TESTED_TAG not found, staying on current version"
            }
        else
            git pull origin main 2>/dev/null || warn "Could not pull updates"
        fi
        cd - >/dev/null

        NEW_VER=$(read_hermes_version)
        if [ "$CURRENT_VER" != "$NEW_VER" ]; then
            log "Updated: $CURRENT_VER → $NEW_VER"
            check_hermes_compat "$NEW_VER"
        else
            log "Already at latest compatible version ($CURRENT_VER)"
        fi
    fi
else
    log "Installing Hermes Agent..."
    mkdir -p "$HERMES_HOME"
    if [ -n "$HERMES_TESTED_TAG" ]; then
        git clone --depth 1 --branch "$HERMES_TESTED_TAG" "$HERMES_REPO" "$HERMES_AGENT_DIR"
    else
        git clone --depth 1 "$HERMES_REPO" "$HERMES_AGENT_DIR"
    fi
    log "Hermes Agent cloned"

    FRESH_VER=$(read_hermes_version)
    check_hermes_compat "$FRESH_VER"
fi

if [ ! -f "$VENV_DIR/bin/pip" ]; then
    log "Creating Python virtual environment..."
    rm -rf "$VENV_DIR"
    python3 -m venv "$VENV_DIR"
fi

log "Installing Hermes dependencies..."
"$VENV_DIR/bin/pip" install -q --upgrade pip
"$VENV_DIR/bin/pip" install -q -e "$HERMES_AGENT_DIR"

# markitdown-mcp (Microsoft official) — converts files (PDF/DOCX/XLSX/audio/...)
# to Markdown so sub-agents don't burn tokens on binary content. Pulled from
# PyPI (auto-updates on every install.sh run).
log "Installing markitdown-mcp..."
if "$VENV_DIR/bin/pip" install -q --upgrade markitdown-mcp 2>/dev/null; then
    log "markitdown-mcp installed/updated"
    MARKITDOWN_BIN="$VENV_DIR/bin/markitdown-mcp"
    if [ ! -x "$MARKITDOWN_BIN" ]; then
        warn "markitdown-mcp binary not found at $MARKITDOWN_BIN after install"
        MARKITDOWN_BIN=""
    fi
else
    warn "markitdown-mcp install failed (continuing without it)"
    MARKITDOWN_BIN=""
fi

mkdir -p "$HOME/.local/bin"
ln -sf "$VENV_DIR/bin/hermes" "$HOME/.local/bin/hermes"
log "Linked hermes -> ~/.local/bin/hermes"

if [[ ":$PATH:" != *":$HOME/.local/bin:"* ]]; then
    echo 'export PATH="$HOME/.local/bin:$PATH"' >> "$HOME/.bashrc"
    export PATH="$HOME/.local/bin:$PATH"
    log "Added ~/.local/bin to PATH"
fi

FINAL_VER=$(read_hermes_version)
log "Hermes Agent v$FINAL_VER ready"

# ============================================================================
header "Step 3/10: OpenCode Go Provider"
# ============================================================================

# Make sure ~/.local/bin (where we drop OpenCode/Engram symlinks) is on PATH
# so subsequent steps + future shells can find them.
mkdir -p "$HOME/.local/bin"
if [[ ":$PATH:" != *":$HOME/.local/bin:"* ]]; then
    if ! grep -q '\.local/bin' "$HOME/.bashrc" 2>/dev/null; then
        echo 'export PATH="$HOME/.local/bin:$PATH"' >> "$HOME/.bashrc"
    fi
    export PATH="$HOME/.local/bin:$PATH"
fi

if [ "$HAS_NPM" -eq 1 ]; then
    if ! command -v opencode &>/dev/null; then
        log "Installing OpenCode CLI (opencode-ai on npm)..."
        # Correct npm package is `opencode-ai` (binary: `opencode`).
        # Older fallbacks left for backwards compat with mis-named registries.
        if npm install -g opencode-ai 2>/dev/null \
            || npm install -g opencode 2>/dev/null \
            || npm install -g @sst-software/opencode 2>/dev/null; then

            # On non-root npm installs, the global bin directory is usually
            # `$(npm prefix -g)/bin` (e.g. ~/.nvm/versions/node/*/bin or
            # ~/.npm-global/bin). That dir is NOT always in the user's PATH,
            # so a fresh install can leave `opencode` installed but invisible.
            # Symlink it into ~/.local/bin (which we just added to PATH).
            NPM_GLOBAL_BIN=""
            if command -v npm &>/dev/null; then
                NPM_PREFIX=$(npm prefix -g 2>/dev/null || true)
                if [ -n "$NPM_PREFIX" ] && [ -x "$NPM_PREFIX/bin/opencode" ]; then
                    NPM_GLOBAL_BIN="$NPM_PREFIX/bin/opencode"
                fi
            fi
            if [ -z "$NPM_GLOBAL_BIN" ]; then
                # Fallback: scan a few common locations
                for candidate in \
                    "$HOME/.npm-global/bin/opencode" \
                    "$HOME/.nvm/versions/node/"*/bin/opencode \
                    "/usr/local/bin/opencode" \
                    "/usr/bin/opencode"; do
                    if [ -x "$candidate" ]; then
                        NPM_GLOBAL_BIN="$candidate"
                        break
                    fi
                done
            fi

            if [ -n "$NPM_GLOBAL_BIN" ]; then
                ln -sf "$NPM_GLOBAL_BIN" "$HOME/.local/bin/opencode"
                hash -r 2>/dev/null || true
            fi

            if command -v opencode &>/dev/null; then
                log "OpenCode CLI installed ($(command -v opencode))"
            else
                warn "OpenCode CLI install reported success but the binary is unreachable."
                warn "Find it with: npm prefix -g (look in <prefix>/bin/opencode)"
                warn "and symlink it: ln -sf <path> ~/.local/bin/opencode"
            fi
        else
            warn "OpenCode CLI install failed. You'll need to configure the provider manually."
            warn "Set model.base_url in ~/.hermes/config.yaml to your provider's endpoint."
        fi
    else
        log "OpenCode CLI already installed ($(command -v opencode))"
    fi
fi

log "Provider will be configured in Step 6"

# ============================================================================
header "Step 4/10: Source Patch (delegate_tool.py)"
# ============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"

if [ -d "$SCRIPT_DIR/src" ] && [ -f "$SCRIPT_DIR/src/__init__.py" ]; then
    COBALT_TMP="$SCRIPT_DIR"
    log "Using local source files ($SCRIPT_DIR)"
else
    log "Fetching cobalt-agent source from GitHub..."
    if [ -d "$COBALT_TMP" ]; then
        rm -rf "$COBALT_TMP"
    fi
    git clone --depth 1 "$COBALT_REPO" "$COBALT_TMP" 2>/dev/null || {
        err "Cannot fetch cobalt-agent source and no local files found"
        exit 1
    }
fi

PATCH_SCRIPT="$COBALT_TMP/patches/apply_routing_patch.py"
if [ -f "$PATCH_SCRIPT" ]; then
    PATCH_STATUS=$("$VENV_DIR/bin/python" "$PATCH_SCRIPT" verify 2>&1 || true)
    if echo "$PATCH_STATUS" | grep -qi "applied\|verified\|true"; then
        log "Source patch already applied (idempotent check passed)"
        log "Re-applying to ensure latest version..."
    fi
    "$VENV_DIR/bin/python" "$PATCH_SCRIPT" apply || {
        warn "Patch apply returned non-zero — checking if already applied..."
        if "$VENV_DIR/bin/python" "$PATCH_SCRIPT" verify 2>/dev/null; then
            log "Patch verified OK (was already applied)"
        else
            warn "Patch could not be applied or verified (routing will use inference fallback)"
        fi
    }
else
    warn "Patch script not found, skipping (routing will use inference only)"
fi

# ============================================================================
header "Step 5/10: cobalt-routing Plugin"
# ============================================================================

if [ "$IS_UPDATE" -eq 1 ] && [ -f "$PLUGIN_DIR/__init__.py" ]; then
    OLD_PLUGIN_VER=$(python3 -c "
import re
text = open('$PLUGIN_DIR/__init__.py').read()
m = re.search(r'PLUGIN_VERSION\s*=\s*\"(.*?)\"', text)
